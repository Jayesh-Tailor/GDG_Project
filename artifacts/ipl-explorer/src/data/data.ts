export interface RecentForm {
  match: string;
  score: number | null;
  wickets: number | null;
}

export interface BattingStats {
  runs: number;
  average: number;
  strikeRate: number;
  highestScore: number;
  fifties: number;
  hundreds: number;
  matches: number;
}

export interface BowlingStats {
  wickets: number;
  economy: number;
  bestFigures: string;
  average: number;
  matches: number;
}

export interface MatchupStat {
  team: string;
  runs?: number;
  wickets?: number;
  average?: number;
}

export interface ImpactMetrics {
  deathOversStrikeRate?: number;
  dotBallPercent?: number;
  boundaryPercent?: number;
}

export interface FantasyMetrics {
  fantasyRating: number;
  consistencyScore: number;
}

export interface Player {
  id: string;
  name: string;
  age: number;
  role: "Batsman" | "Bowler" | "All-rounder" | "Wicket-keeper";
  team: string;
  battingStyle: string;
  bowlingStyle: string;
  image: string;
  rating: number;
  injuryStatus: "Fit" | "Doubtful" | "Out";
  playingProbability: number;
  batting: BattingStats;
  bowling: BowlingStats | null;
  recentForm: RecentForm[];
  highlights: { bestSeason: string; careerHigh: string; awards: string[] };
  insights: { strengths: string[]; weaknesses: string[]; roleTag: string };
  matchups: MatchupStat[];
  homeAvg: number;
  awayAvg: number;
  impact: ImpactMetrics;
  fantasy: FantasyMetrics;
}

